/** Íconos disponibles para categorías financieras (clave -> componente). */
export const ICONOS_FINANZAS: Record<string, LucideIcon> = {
    jornales: Users,
    abonos: Sprout,
    control: Bug,
    transporte: Truck,
    herramientas: Wrench,
    beneficio: Droplets,
    cafe: Coffee,
    mercado: ShoppingBasket,
    servicios: Zap,
    educacion: GraduationCap,
    salud: HeartPulse,
    transporteFam: Bus,
    ropa: Shirt,
    deudas: CreditCard,
    casa: Home,
    jornal: HardHat,
    negocio: Store,
    remesa: HandCoins,
    ahorro: PiggyBank,
    otro: Wallet,
};

export function iconoDe(clave: string): LucideIcon {
    return ICONOS_FINANZAS[clave] || Wallet;
}

